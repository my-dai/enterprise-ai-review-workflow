  console.log('PASS missing facts produce questions without an apply action');
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await page.getByRole('button', { name: 'Find related experience' }).click();
  await page.getByRole('textbox', { name: 'Search library content' }).fill('electrical');
  await page.getByText('Proposed check: confirm cable tray', { exact: false }).first().waitFor();
  await page.getByRole('checkbox', { name: 'Use as a reference for AI revisions' }).check();
  await page.getByRole('button', { name: 'Suggest revision', exact: true }).nth(1).click();
  await page.getByRole('button', { name: 'Apply to this field' }).waitFor();
  const original = await page.locator('#recommendation').inputValue();
  assert(!original.startsWith('Proposed improvement'));
  await page.screenshot({ path: 'local-review-evidence/03-source-backed-field-revision.png', fullPage: true });
  await page.getByRole('button', { name: 'Apply to this field' }).click();
  assert((await page.locator('#recommendation').inputValue()).startsWith('Proposed improvement'));
  await page.getByRole('button', { name: 'Undo AI revision' }).click();
  assert.equal(await page.locator('#recommendation').inputValue(), original);
  console.log('PASS source content is selectable; revisions require acceptance and can be undone');
  await page.getByRole('button', { name: 'Suggest revision', exact: true }).nth(1).click();
  await page.getByRole('button', { name: 'Apply to this field' }).waitFor();
  await page.getByRole('button', { name: 'Remove reference Coordinate cable tray before ceiling closure' }).click();
  assert(await page.getByRole('button', { name: 'Apply to this field' }).isDisabled());
  console.log('PASS changing reference selection invalidates the suggestion');
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await page.getByRole('button', { name: 'Suggest revision', exact: true }).nth(1).click();
  await page.locator('#recommendation').fill('My newer manual wording.');
  await page.getByRole('button', { name: 'Apply to this field' }).waitFor();
  assert(await page.getByRole('button', { name: 'Apply to this field' }).isDisabled());
  console.log('PASS edits during AI generation cannot be overwritten by a late result');
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await page.locator('#response-mode').selectOption('error');
  await page.getByRole('button', { name: 'Suggest revision', exact: true }).nth(1).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.locator('#recommendation').inputValue(), 'My newer manual wording.');
  console.log('PASS service errors preserve author text');
